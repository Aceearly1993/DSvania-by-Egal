; This adds a check to change the player outline color based
; on the currently equipped chestplate.
; The table consists of the literal hex value for the color.
; A value of 0x00 will use the default outline color in character
; data.
; by EgalLau37

Overlay86Start equ 0x22EB1A0
FreeSpace equ Overlay86Start+0x2300


.open "ftc/arm9.bin", 0x2000000

.org 0x204D96C
b UpdatePlayerOutline

.close


.open "ftc/overlay9_86", Overlay86Start

.org FreeSpace

UpdatePlayerOutline:
ldr r2,=0x20FFC58
ldrb r2,[r2,0xB3A]
cmp r2,0x0
ldrneh r1,[r1,0x44]
bxne r12
ldr r2,=0x2100258
ldrh r2,[r2,0x70]
ldr r3,=ChestplateToOutlineTable
add r3,r2,lsl 0x1
ldrh r3,[r3]
cmp r3,0x0
ldreqh r1,[r1,0x44]
movne r1,r3
bx r12
.pool


ChestplateToOutlineTable:
.dh 0x0	;0x0	;(nothing)
.dh 0x0	;0x1
.dh 0x0	;0x2
.dh 0x0	;0x3
.dh 0x0	;0x4
.dh 0x0	;0x5
.dh 0x0	;0x6
.dh 0x0	;0x7
.dh 0x0	;0x8
.dh 0x0	;0x9
.dh 0x0	;0xA
.dh 0x0	;0xB
.dh 0x0	;0xC
.dh 0x0	;0xD
.dh 0x0098	;0xE	;Barbarian belt
.dh 0x0	;0xF
.dh 0x0	;0x10
.dh 0x0	;0x11
.dh 0x0	;0x12
.dh 0x0	;0x13
.dh 0x0	;0x14
.dh 0x0	;0x15
.dh 0x0	;0x16
.dh 0x0	;0x17
.dh 0x0	;0x18
.dh 0x0	;0x19
.dh 0x0	;0x1A
.dh 0x0	;0x1B
.dh 0x0	;0x1C
.dh 0x0	;0x1D
.dh 0x0	;0x1E
.dh 0x0	;0x1F
.dh 0x0	;0x20
.dh 0x0	;0x21
.dh 0x0	;0x22
.dh 0x0	;0x23
.dh 0x0	;0x24
.dh 0x0	;0x25
.dh 0x0	;0x26
.dh 0x0	;0x27

.close